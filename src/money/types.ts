// Lifeline — data model. Everything is stored on the user's phone only (localStorage).

export type Freq = "monthly" | "weekly" | "yearly" | "one-off";

export type LoanType =
  | "home" | "personal" | "car" | "two-wheeler" | "education" | "gold"
  | "credit-card" | "bnpl" | "consumer-durable" | "business" | "other";

export interface Account {
  id: string;
  name: string;          // e.g. "HDFC Salary A/c"
  balance: number;       // last known balance
  minBalance: number;    // amount the bank requires you to keep (avoid charges)
  updatedAt: string;     // ISO date of last balance update
}

export interface Loan {
  id: string;
  name: string;          // e.g. "Bike loan"
  lender: string;
  type: LoanType;
  emi: number;           // monthly instalment (for credit cards: the amount you plan to pay)
  dueDay: number;        // 1–31, day of month the auto-debit happens
  accountId: string;     // which bank account the EMI is debited from
  outstanding: number;   // principal still owed
  ratePct: number;       // annual interest rate %
  paidMonths: string[];  // "YYYY-MM" months the user confirmed as paid
  cardId?: string;       // set on the monthly payment generated from a detailed credit card
  monthlyCost?: number;  // card payments: monthly outgo excluding everyday spends (avoids double counting)
}

// ─── Credit cards ───────────────────────────────────────────────────────────
/** A purchase or balance converted to EMI on a credit card. */
export interface CardEmi {
  id: string;
  label: string;         // e.g. "iPhone" or "Balance conversion"
  principal: number;
  ratePct: number;       // annual, reducing balance
  tenure: number;        // months
  processingFee: number; // ₹ (GST added on top)
  startYm: string;       // statement month of the first instalment, "YYYY-MM"
}

/** Money taken out of the card: ATM withdrawal, or paying rent / loans / wallets through an app for a fee. */
export interface CardCashOut {
  id: string;
  date: string;          // ISO
  amount: number;        // money received / paid onward
  method: "atm" | "app";
  feePct: number;
  feeIncludesGst: boolean;
  note: string;
}

export interface CardStatement {
  ym: string; date: string; due: string;
  tad: number;           // total amount due
  mad: number;           // minimum amount due
  paidAmount: number;
  estimated: boolean;    // generated by Lifeline (true) or typed in from the bank statement (false)
}

export interface CreditCard {
  id: string;
  name: string;
  bank: string;
  limit: number;
  statementDay: number;
  dueDay: number;
  accountId: string;     // bank account the bill is paid from
  monthlyRatePct: number; // finance charge per month (e.g. 3.6)
  revolving: number;     // unpaid balance carried from earlier statements
  unbilled: number;      // spends since the last statement
  plan: "full" | "minimum" | "custom";
  customPay: number;
  minPct: number;        // minimum due % of non-EMI principal
  minFloor: number;      // minimum due never below this (₹)
  lateFee: number;
  atmFeePct: number;
  atmMinFee: number;
  emis: CardEmi[];
  cashOuts: CardCashOut[];
  paidMonths: string[];
  lastStatement: CardStatement | null;
  cycleYm: string;       // month of the last statement Lifeline has accounted for
}

export type IncomeKind = "salary" | "business" | "freelance" | "rental" | "family" | "side-income" | "other";

export interface Income {
  id: string;
  source: string;
  kind: IncomeKind;
  amount: number;
  freq: Freq;
  day?: number;          // pay day (monthly)
  accountId?: string;
}

export type ExpenseCategory =
  | "rent" | "groceries" | "utilities" | "transport" | "education" | "medical" | "insurance"
  | "family-support" | "subscriptions" | "eating-out" | "shopping" | "entertainment"
  | "personal-care" | "travel" | "other";

export interface Expense {
  id: string;
  name: string;
  category: ExpenseCategory;
  amount: number;
  freq: Freq;
  essential: boolean;
}

export interface EarnProfile {
  skills: string[];      // tags from SKILL_TAGS
  hoursPerWeek: number;
  urgency: "this-month" | "3-months" | "long-term";
  languages: string;     // free text, e.g. "Hindi, English"
  shortlist: string[];   // opportunity ids the user wants to try
}

export interface Settings {
  bufferDays: number;    // fund the account this many days before the due date
  bounceFee: number;     // typical bounce/NACH-return charge per failed EMI (incl. GST)
  remindersOn: boolean;
  name: string;          // used for greeting and lender letters
  hideAmounts: boolean;  // privacy mode
  theme: "system" | "light" | "dark";
  setupDismissed: boolean;
  calendarAdded: boolean;  // user downloaded/added calendar reminders
  autoLockSec: number;     // lock after this many seconds in background (0 = immediately)
  blockScreenshots: boolean; // Android: hide from recents and block screenshots
  bioEnabled: boolean;     // Android: fingerprint / face unlock
  plan: Plan;
  aiShare: "exact" | "rounded" | "none"; // how amounts appear in summaries shared with AI apps
}

export type Plan = "free" | "early-access" | "pro";

/** Keys for services the user connects. Stored inside the encrypted vault only. */
export interface Integrations {
  anthropicKey: string;    // Claude API key for the built-in assistant
  alphaVantageKey: string; // free stock-price key from alphavantage.co
}

export type HoldingKind = "stock" | "mf" | "fd" | "gold" | "epf" | "crypto" | "other";

export interface Holding {
  id: string;
  kind: HoldingKind;
  name: string;
  symbol?: string;       // stocks: e.g. RELIANCE.BSE or AAPL (Alpha Vantage format)
  schemeCode?: string;   // mutual funds: AMFI scheme code (from mfapi.in)
  units: number;         // stocks/MF/crypto units; 1 for amount-based assets
  avgPrice: number;      // cost per unit (or amount invested for FD/gold/EPF)
  lastPrice?: number;    // latest market price per unit
  priceAt?: string;      // ISO time of lastPrice
  manualValue?: number;  // current value for assets without live prices
  liquid: boolean;       // can be withdrawn within a few days without heavy penalty
}

export interface MoneyState {
  version: 1;
  accounts: Account[];
  loans: Loan[];
  incomes: Income[];
  expenses: Expense[];
  profile: EarnProfile;
  settings: Settings;
  holdings: Holding[];
  integrations: Integrations;
  cards: CreditCard[];
}

